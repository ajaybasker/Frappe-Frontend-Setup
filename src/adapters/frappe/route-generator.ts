import * as path from 'node:path';
import * as fs from 'node:fs';

export interface RouteGenerationResult {
  pyCreated: boolean;
  pyPath: string;
  pyBackupPath?: string;
  htmlCreated: boolean;
  htmlPath: string;
  htmlBackupPath?: string;
}

/**
 * Generates www/<route>.py and www/<route>.html portal files in the Frappe custom app.
 */
export function generatePortalRoute(
  appPkgDir: string,
  appName: string,
  route: string,
  dryRun: boolean = false
): RouteGenerationResult {
  const wwwDir = path.join(appPkgDir, 'www');
  const pyPath = path.join(wwwDir, `${route}.py`);
  const htmlPath = path.join(wwwDir, `${route}.html`);

  const pyContent =
`# Generated by frappe-frontend-cli for route '/${route}'
import frappe

no_cache = 1

def get_context(context):
    csrf_token = frappe.sessions.get_csrf_token()
    frappe.db.commit()
    context.csrf_token = csrf_token
    context.boot = get_boot()
    return context

def get_boot():
    return {
        "site_name": getattr(frappe.local, "site", ""),
        "read_only_mode": getattr(frappe.flags, "read_only_mode", False),
        "csrf_token": frappe.sessions.get_csrf_token() if hasattr(frappe, "sessions") else "",
    }
`;

  const htmlContent =
`<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>{{ app_title or "${appName} Frontend" }}</title>
    <script>
      window.frappe = window.frappe || {};
      frappe.csrf_token = "{{ csrf_token }}";
      frappe.boot = {{ boot | tojson }};
    </script>
    {# Render Vite production entry if index.html exists #}
    {% set app_index = frappe.get_app_path("${appName}", "public", "frontend", "index.html") %}
    {% if frappe.read_file(app_index) %}
      {{ frappe.read_file(app_index) | safe }}
    {% else %}
      <div id="app"></div>
    {% endif %}
  </head>
  <body>
  </body>
</html>
`;

  let pyCreated = false;
  let pyBackupPath: string | undefined;
  let htmlCreated = false;
  let htmlBackupPath: string | undefined;

  if (!dryRun) {
    if (!fs.existsSync(wwwDir)) {
      fs.mkdirSync(wwwDir, { recursive: true });
    }

    if (fs.existsSync(pyPath)) {
      const existingPy = fs.readFileSync(pyPath, 'utf8');
      if (existingPy !== pyContent) {
        pyBackupPath = `${pyPath}.bak.${Date.now()}`;
        fs.writeFileSync(pyBackupPath, existingPy, 'utf8');
        fs.writeFileSync(pyPath, pyContent, 'utf8');
        pyCreated = true;
      }
    } else {
      fs.writeFileSync(pyPath, pyContent, 'utf8');
      pyCreated = true;
    }

    if (fs.existsSync(htmlPath)) {
      const existingHtml = fs.readFileSync(htmlPath, 'utf8');
      if (existingHtml !== htmlContent) {
        htmlBackupPath = `${htmlPath}.bak.${Date.now()}`;
        fs.writeFileSync(htmlBackupPath, existingHtml, 'utf8');
        fs.writeFileSync(htmlPath, htmlContent, 'utf8');
        htmlCreated = true;
      }
    } else {
      fs.writeFileSync(htmlPath, htmlContent, 'utf8');
      htmlCreated = true;
    }
  } else {
    pyCreated = !fs.existsSync(pyPath);
    htmlCreated = !fs.existsSync(htmlPath);
  }

  return {
    pyCreated,
    pyPath,
    pyBackupPath,
    htmlCreated,
    htmlPath,
    htmlBackupPath,
  };
}
